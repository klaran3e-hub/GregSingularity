function icon(id, colors, lines) {
  const pixels = Buffer.alloc(16 * 16 * 4)
  if (lines.length !== 16 || lines.some(line => line.length !== 16)) throw Error(id + ' grid')
  lines.forEach((line,y) => [...line].forEach((ch,x) => {
    if (ch === '.') return
    const at = 4*(16*y+x)
    pixels.writeUIntBE(colors[Number(ch)],at,3)
    pixels[at+3] = 255
  }))
  writeFileSync(new URL(id+'.png',folder),png(16,16,pixels))
}


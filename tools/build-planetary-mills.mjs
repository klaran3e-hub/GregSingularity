import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pack = fileURLToPath(new URL('../pack/overrides/kubejs/', import.meta.url))
const deposits = JSON.parse(readFileSync(new URL('./planetary-mills.json', import.meta.url), 'utf8'))
const data = 'data/zero_shift/'
const stages = {
  grit: ['Дроблёная порода', 'crushed ore'], washed: ['Промытая фракция', 'washed fraction'],
  heavy: ['Тяжёлый концентрат', 'heavy concentrate'], crystal: ['Кристаллизат', 'precipitated crystals'],
  assay: ['Прокалённый концентрат', 'calcined concentrate'], liquor: ['Продуктивный раствор', 'pregnant liquor']
}
const get = file => JSON.parse(readFileSync(resolve(pack, file+'.json'),'utf8'))
function save(file, value) {
  const path = resolve(pack, file+'.json')
  mkdirSync(dirname(path), {recursive:true})
  writeFileSync(path, JSON.stringify(value,null,2)+'\n')
}
const registry = deposits.map(({id,world,ore,count,eu,heat,wash,split,water,solvent,mineral,gangue}) =>
  ({id,world,ore,count,eu,heat,wash,split,water,solvent,mineral,gangue}))
const generated = '// Generated by tools/build-planetary-mills.mjs from tools/planetary-mills.json.\n'
const newBlocks = deposits.filter(d => d.world.startsWith('ad_astra:'))
writeFileSync(resolve(pack,'startup_scripts/planetary_deposits.js'), generated +
  'global.gtibdPlanetaryMills = [\n' + registry.map(d=>'  '+JSON.stringify(d)).join(',\n')+'\n]\n'+
  "StartupEvents.registry('item', event => {\n  global.gtibdPlanetaryMills.forEach(site => {\n    ;['grit','washed','heavy','crystal','assay'].forEach(form => {\n      const id = 'mill_' + site.id + '_' + form\n      event.create(id).texture('kubejs:item/' + id)\n    })\n  })\n})\n"+
  "StartupEvents.registry('fluid', event => {\n  global.gtibdPlanetaryMills.forEach(site => {\n    const id = 'mill_' + site.id + '_liquor'\n    event.create(id).stillTexture('kubejs:block/'+id+'_still').flowingTexture('kubejs:block/'+id+'_flow').noBlock().noBucket().viscosity(1250)\n  })\n})\n"+
  "StartupEvents.registry('block', event => {\n  for (const id of "+JSON.stringify(newBlocks.map(s=>s.ore))+")\n    event.create(id).stoneSoundType().hardness(5).resistance(7).requiresTool(true).textureAll('kubejs:block/'+id)\n      .tagBlock('minecraft:mineable/pickaxe').tagBlock('minecraft:needs_diamond_tool')\n})\n")
for(const site of newBlocks) {
  const base=site.feature || 'venus_tantalite', feature='field_'+site.id
  const ores=get(data+'worldgen/configured_feature/'+base)
  ores.config.size=site.id==='moon'?10:8
  ores.config.discard_chance_on_air_exposure=.55
  ores.config.targets=[{target:{predicate_type:'minecraft:tag_match',tag:'ad_astra:'+site.id+'_stone_replaceables'},state:{Name:'kubejs:'+site.ore}}]
  save(data+'worldgen/configured_feature/'+feature, ores)
  const placed=get(data+'worldgen/placed_feature/'+base)
  placed.feature='zero_shift:'+feature
  placed.placement[0].count=4
  placed.placement[2].height.min_inclusive.absolute=16
  placed.placement[2].height.max_inclusive.absolute=52
  save(data+'worldgen/placed_feature/'+feature,placed)
  const biomes=get(data+'forge/biome_modifier/'+base)
  if(site.id==='mercury')biomes.biomes=['ad_astra:mercury_deltas']
  biomes.features='zero_shift:'+feature
  save(data+'forge/biome_modifier/'+feature,biomes)
}
for(const [idx,lang] of ['ru_ru','en_us'].entries()) {
  const file='assets/kubejs/lang/'+lang,strings=get(file)
  for(const s of deposits) {
    if(newBlocks.includes(s))strings['block.kubejs.'+s.ore]=idx?s.ore_en:s.ore_ru
    for(const [stage,names] of Object.entries(stages)) {
      const key=(stage==='liquor'?'fluid':'item')+'.kubejs.mill_'+s.id+'_'+stage
      strings[key]=idx?s.id[0].toUpperCase()+s.id.slice(1)+' '+names[1]:names[0]+' '+s.origin
    }
  }
  save(file,strings)
}
